const bySlug = Object.fromEntries(items.map(x => [x.s, x]))
// priority = height in the dependency DAG (critical path first); docs before ADRs at equal height
const children = {}
for (const it of items) for (const dep of it.d) (children[dep] = children[dep] || []).push(it.s)
const heightMemo = {}
const height = (s) => heightMemo[s] ?? (heightMemo[s] = 1 + Math.max(0, ...(children[s] || []).map(height)))
const running = {}
function schedule(it) {
  if (running[it.s]) return running[it.s]
  running[it.s] = (async () => {
    const deps = await Promise.all(it.d.map(dep => schedule(bySlug[dep])))
    const blocked = it.d.filter((dep, i) => !deps[i] || deps[i].dry)
    if (blocked.length) {
      log(`${dryRun ? 'DRY' : 'SKIP'} ${it.s}: waiting on ${blocked.join(', ')}`)
      return dryRun ? { dry: true, slug: it.s, next: 'blocked' } : null
    }
    try {
      const r = await chain(it, height(it.s) * 10 + (it.kind === 'doc' ? 1 : 0))
      if (dryRun) log(`DRY ${it.s}: complete from seed, status ${r.status}`)
      return r
    } catch (e) {
      if (e instanceof DryStop) { log(`DRY ${it.s}: next live stage ${e.label}`); return { dry: true, slug: it.s, next: e.label } }
      log(`FAILED ${it.s}: ${e.message || e}`)
      return null
    }
  })()
  return running[it.s]
}
const results = await Promise.all(items.map(schedule))
if (dryRun) return { dry: items.map((it, i) => results[i] && results[i].dry ? { slug: it.s, next: results[i].next } : { slug: it.s, next: 'complete', status: results[i] && results[i].status }) }
const ok = results.filter(Boolean)
const failed = items.filter((it, i) => !results[i]).map(it => it.s)
if (failed.length) log(`NOT COMPLETED: ${failed.join(', ')}`)
log(`waves: ${ok.length}/${items.length} items complete; escalated: ${ok.filter(r => r.escalations.length).map(r => r.slug).join(', ') || 'none'}`)
return { halted: HALT, items: ok, failed }
