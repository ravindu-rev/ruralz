async function review(it, P) {
  const vs = await Promise.all(it.l.map(L => limited(reviewPrompt(it, L), { label: `review:${it.s}:${L}`, phase: 'Review', model: M, effort: 'high', schema: VERDICT }, P)))
  vs.forEach((v, i) => must(v, `review:${it.s}:${it.l[i]}`))
  return vs
}

async function revise(vs, it, P) {
  const blocking = vs.flatMap(v => v.blocking)
  const blockingLenses = it.l.filter((L, i) => vs[i].blocking.length)
  if (!blocking.length) return { verdicts: vs, blockingLenses, disputes: [] }
  const r = must(await limited(
    `${ctxFor(it)}\n\nRevise ${repo}/${it.p} in place. Blocking findings you MUST address (or dispute with a specific reason): ${JSON.stringify(blocking)}. Non-blocking suggestions worth applying: ${JSON.stringify(vs.flatMap(v => v.non_blocking || []).slice(0, 25))}. Keep the mandated H2s. ${frontMatterRule(it)} ${VERIFY(it.p)} Do not edit any other file.`,
    { label: `revise:${it.s}`, phase: 'Revise', model: M, effort: 'high', schema: REVISE_SCHEMA }, P), `revise:${it.s}`)
  return { verdicts: vs, blockingLenses, disputes: r.disputed || [] }
}

async function rereview(st, it, P) {
  if (!st.blockingLenses.length) return { ...st, second: [] }
  const second = await Promise.all(st.blockingLenses.map(L => {
    const prev = st.verdicts[it.l.indexOf(L)].blocking
    const disputed = st.disputes.filter(d => String(d.id).startsWith(`${L}-`))
    return limited(
      reviewPrompt(it, L, `This is a RE-REVIEW after revision. Previous blocking items for your lens: ${JSON.stringify(prev)}.${disputed.length ? ` The reviser disputed these with reasons; accept a dispute only if the reason holds: ${JSON.stringify(disputed)}.` : ''} Do not re-list resolved items; list only items still blocking and new regressions.`),
      { label: `rereview:${it.s}:${L}`, phase: 'Revise', model: M, effort: 'high', schema: VERDICT }, P)
  }))
  second.forEach((v, i) => must(v, `rereview:${it.s}:${st.blockingLenses[i]}`))
  return { ...st, second }
}

async function revise2(st, it, P) {
  const blocking = st.second.flatMap(v => v.blocking)
  if (!blocking.length) return { ...st, escalations: [] }
  const r = must(await limited(
    `${ctxFor(it)}\n\nFINAL revision of ${repo}/${it.p}. Remaining blocking findings: ${JSON.stringify(blocking)}. Address each or dispute with a precise reason; disputed items MUST be added to the Open questions table (IDs OQ-<docslug>-<n>; for ADRs add them under More information). Report in disputed only blocking finding ids you did not fix. ${frontMatterRule(it)} ${VERIFY(it.p)} Do not edit any other file.`,
    { label: `revise2:${it.s}`, phase: 'Revise', model: M, effort: 'high', schema: REVISE_SCHEMA }, P), `revise2:${it.s}`)
  const ids = new Set(blocking.map(b => b.id))
  return { ...st, escalations: (r.disputed || []).filter(d => ESC_RE.test(String(d.id)) && ids.has(String(d.id).match(ESC_RE)[0])) }
}

function finalize(st, it) {
  const status = it.kind === 'adr' ? 'adr' : (st.escalations.length ? 'approved-with-escalations' : 'reviewed')
  if (st.escalations.length) log(`ESCALATIONS ${it.s}: ${st.escalations.map(e => e.id).join(', ')}`)
  return { slug: it.s, path: it.p, kind: it.kind, status, escalations: st.escalations,
    scores: st.verdicts.map((v, i) => ({ lens: it.l[i], score: v.score, verdict: v.verdict })) }
}

async function chain(it, P) {
  must(await write(it, P), `write:${it.s}`)
  const v = await review(it, P)
  const r1 = await revise(v, it, P)
  const r2 = await rereview(r1, it, P)
  const r3 = await revise2(r2, it, P)
  return finalize(r3, it)
}

