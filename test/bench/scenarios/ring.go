// Balancer budget rules (docs/architecture/09-traffic-management-and-resilience.md
// "Load balancing"), targets: every ring takes v virtual nodes per
// Endpoint, v = clamp(floor((256 MiB - schedules - 16 MiB) / (16 B x
// Endpoints over rings)), 64, 1,024); when v = 64 does not fit, rings fall
// back to weighted random with degraded reason balancer_budget.
const (
	BalancerBudget      = 256 << 20
	balancerReserve     = 16 << 20
	balancerVNodeBytes  = 16
	balancerMinVNodes   = 64
	ringFirstEndpointAt = 20000
)

// RingFits reports whether rings Upstreams of endpoints Endpoints each fit
// the balancer budget at the minimum of 64 virtual nodes per Endpoint.
func RingFits(rings, endpoints int) bool {
	return (BalancerBudget-balancerReserve)/(balancerVNodeBytes*rings*endpoints) >= balancerMinVNodes
}

// ringBundle writes the ring-hash ladder's Bundle into dir: S1's Gateway,
// mock Upstream and bench-1k Route on the lab, plus rings ring-hash
// Upstreams of endpoints static Endpoints each, every one reached by a
// Route of its own, so each gets its balancer structure (PBB "Constants
// the suite verifies": the ring-hash Upstream ladder).
func ringBundle(dir string, l gen.Lab, rings, endpoints int) error {
	var b bytes.Buffer
	b.WriteString("# The ring-hash Upstream ladder's Bundle, generated by test/bench/scenarios.\n")
	b.WriteString("apiVersion: ruralz/v1alpha1\nkind: Gateway\nmetadata:\n  name: bench\nspec:\n")
	b.WriteString("  listeners:\n    - name: http\n      protocol: http\n      port: 8080\n  admin:\n    port: 9901\n")
	b.WriteString("  telemetry:\n    otlp:\n      endpoint: " + strconv.Quote(l.OTLPEndpoint) + "\n")
	if l.OTLPCA != "" {
		b.WriteString("      tls:\n        caCertificate: {secretRef: {provider: file, name: " + l.OTLPCA + "}}\n")
	}
	b.WriteString("    traceSampling: 0.01\n")
	doc := func(kind, name string) {
		b.WriteString("---\napiVersion: ruralz/v1alpha1\nkind: " + kind + "\nmetadata:\n  name: " + name + "\nspec:\n")
	}
	doc("Upstream", "mock")
	b.WriteString("  protocol: http\n  endpoints:\n    - address: " + strconv.Quote(l.MockHost+":"+strconv.Itoa(l.MockPorts[0])) + "\n")
	b.WriteString("  circuitBreaker:\n    maxConnections: 65536\n    maxPendingRequests: 1024\n  timeout: 2s\n")
	doc("Route", gen.BenchRoute)
	b.WriteString("  match:\n    path: {exact: " + gen.BenchPath + "}\n    methods: [GET]\n  upstreams:\n    - name: mock\n  timeout: 5s\n")
	for i := range rings {
		name := "ring-" + strconv.Itoa(i)
		doc("Upstream", name)
		b.WriteString("  protocol: http\n  loadBalancing: {algorithm: ring-hash, hashKey: 'request.headers[\"x-bench-key\"]'}\n  endpoints:\n")
		for e := range endpoints {
			b.WriteString("    - address: " + strconv.Quote(l.MockHost+":"+strconv.Itoa(ringFirstEndpointAt+e)) + "\n")
		}
		doc("Route", name)
		b.WriteString("  match:\n    path: {exact: /ring/" + strconv.Itoa(i) + "}\n  upstreams:\n    - name: " + name + "\n")
	}
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "ruralz.yaml"), b.Bytes(), 0o600)
}

// ringState sums a Node's balancer structures from /debug/upstreams.
type ringState struct {
	bytes                int64
	rings, fallback      int
	minVNodes, maxVNodes int
}

// readRings reads the Node's balancer structures.
func readRings(ctx context.Context, n *harness.Node) (ringState, error) {
	b, err := n.Admin(ctx, "/debug/upstreams")
	if err != nil {
		return ringState{}, err
	}
	var doc adminapi.Upstreams
	if err := json.Unmarshal(b, &doc); err != nil {
		return ringState{}, fmt.Errorf("scenarios: /debug/upstreams: %w", err)
	}
	var st ringState
	for _, u := range doc.Upstreams {
		for _, bl := range u.Balancers {
			st.bytes += bl.Bytes
			if bl.Algorithm != "ring-hash" {
				continue
			}
			st.rings++
			if bl.Fallback {
				st.fallback++
				continue
			}
			if st.minVNodes == 0 || bl.VirtualNodes < st.minVNodes {
				st.minVNodes = bl.VirtualNodes
			}
			st.maxVNodes = max(st.maxVNodes, bl.VirtualNodes)
		}
	}
	return st, nil
}

// ringCriteria judges one rung: every balancer within the 256 MiB budget,
// and the rings either all built with at least 64 virtual nodes or, when
// that does not fit, some falling back with degraded reason
// balancer_budget.
func ringCriteria(rings, endpoints int, st ringState, degraded bool, err error) []benchrecord.BudgetResult {
	prefix := "constants-ring-" + strconv.Itoa(rings)
	if err != nil {
		return []benchrecord.BudgetResult{judge(prefix+"-budget", "balancer structures within 256 MiB (target)", false, err.Error())}
	}
	out := []benchrecord.BudgetResult{
		judge(prefix+"-budget", "balancer structures within 256 MiB (target)", st.bytes <= BalancerBudget,
			fmt.Sprintf("%s over %d rings, %d falling back", mib(st.bytes), st.rings, st.fallback)),
		judge(prefix+"-rings", fmt.Sprintf("a ring for each of the %d ring-hash Upstreams", rings), st.rings == rings, strconv.Itoa(st.rings)+" rings"),
	}
	if RingFits(rings, endpoints) {
		return append(out, judge(prefix+"-fit", "every ring built with 64 to 1,024 virtual nodes per Endpoint (target)",
			st.fallback == 0 && st.minVNodes >= balancerMinVNodes && st.maxVNodes <= 1024,
			fmt.Sprintf("virtual nodes %d to %d, %d falling back", st.minVNodes, st.maxVNodes, st.fallback)))
	}
	return append(out, judge(prefix+"-fallback", "rings beyond the budget fall back to weighted random with degraded reason balancer_budget (target)",
		st.fallback > 0 && degraded, fmt.Sprintf("%d of %d rings fall back, balancer_budget raised %v", st.fallback, st.rings, degraded)))
}
