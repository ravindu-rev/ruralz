// SchemaFile is the source file embedding the published schema, the file
// an N-1 variant's overlay replaces.
const SchemaFile = "api/schema/schema.go"

// schemaViews are the schema files of ruralz/v1alpha1 under api/schema.
func schemaViews() []string {
	return []string{"ruralz/v1alpha1/authoring.schema.json", "ruralz/v1alpha1/rendered.schema.json"}
}

// NMinusOneField names the field V-6's N-1 variant does not know:
// RouteSpec's timeout, which only the OverlayRouteTimeout Bundle sets.
const (
	NMinusOneDef   = "RouteSpec"
	NMinusOneField = "timeout"
)

// WithoutField returns a JSON Schema document with the property field of
// the definition def removed: the schema of a release that predates the
// field, which reports content holding it as newer (RZ-CFG-024).
func WithoutField(doc []byte, def, field string) ([]byte, error) {
	var root map[string]any
	if err := json.Unmarshal(doc, &root); err != nil {
		return nil, fmt.Errorf("chaos: schema: %w", err)
	}
	defs, _ := root["$defs"].(map[string]any)
	d, _ := defs[def].(map[string]any)
	props, _ := d["properties"].(map[string]any)
	if _, ok := props[field]; !ok {
		return nil, fmt.Errorf("chaos: schema has no %s.%s", def, field)
	}
	delete(props, field)
	if req, ok := d["required"].([]any); ok {
		kept := req[:0]
		for _, r := range req {
			if r != field {
				kept = append(kept, r)
			}
		}
		d["required"] = kept
	}
	return json.Marshal(root)
}

// SchemaOverlay returns the source of a replacement for SchemaFile that
// serves views, keyed by their path under api/schema, from string
// constants instead of embedded files.
func SchemaOverlay(views map[string][]byte) string {
	var b strings.Builder
	b.WriteString("// Code generated by the chaos suite for an N-1 variant. DO NOT EDIT.\n\n")
	b.WriteString("package schema\n\nimport (\n\t\"io/fs\"\n\t\"testing/fstest\"\n)\n\n")
	b.WriteString("const (\n")
	b.WriteString("\tauthoringV1alpha1 = " + strconv.Quote(string(views["ruralz/v1alpha1/authoring.schema.json"])) + "\n")
	b.WriteString("\trenderedV1alpha1 = " + strconv.Quote(string(views["ruralz/v1alpha1/rendered.schema.json"])) + "\n")
	b.WriteString(")\n\n")
	b.WriteString("func AuthoringV1alpha1() []byte { return []byte(authoringV1alpha1) }\n\n")
	b.WriteString("func RenderedV1alpha1() []byte { return []byte(renderedV1alpha1) }\n\n")
	b.WriteString("func FS() fs.FS {\n\treturn fstest.MapFS{\n")
	b.WriteString("\t\t\"ruralz/v1alpha1/authoring.schema.json\": {Data: []byte(authoringV1alpha1)},\n")
	b.WriteString("\t\t\"ruralz/v1alpha1/rendered.schema.json\":  {Data: []byte(renderedV1alpha1)},\n")
	b.WriteString("\t}\n}\n")
	return b.String()
}

// NMinusOne returns V-6's N-1 variant: ruralzd of this commit, version
// "0.0.0-n-1", whose schema lacks NMinusOneField, so a Revision setting
// it is newer than the variant serves.
func (h *Harness) NMinusOne(ctx context.Context) (binaries.Set, error) {
	views := map[string][]byte{}
	for _, v := range schemaViews() {
		b, err := os.ReadFile(filepath.Join(h.Root, "api", "schema", filepath.FromSlash(v)))
		if err != nil {
			return binaries.Set{}, fmt.Errorf("chaos: %w", err)
		}
		if views[v], err = WithoutField(b, NMinusOneDef, NMinusOneField); err != nil {
			return binaries.Set{}, err
		}
	}
	dir := filepath.Join(h.binDir, "overlay-n-1")
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return binaries.Set{}, fmt.Errorf("chaos: %w", err)
	}
	src := filepath.Join(dir, "schema.go")
	if err := os.WriteFile(src, []byte(SchemaOverlay(views)), 0o600); err != nil {
		return binaries.Set{}, fmt.Errorf("chaos: %w", err)
	}
	return h.Variant(ctx, "n-1", binaries.BuildOptions{Version: "0.0.0-n-1", Overlay: map[string]string{SchemaFile: src}})
}
