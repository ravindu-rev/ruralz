// ReleaseMilestone is the milestone this release serves. A +ruralz:planned
// marker of pkg/config/v1alpha1 names a later one, which makes its kind,
// field or enum value a feature the serve check refuses, and schemagen
// rejects a marker that does not; a Policy type whose Planned tag is later
// is not Served. schemagen reads the value from this file, so it stays a
// string literal.
const ReleaseMilestone = "M1"

// Feature is one row of the served-feature table, generated by schemagen
// from the +ruralz:planned markers of pkg/config/v1alpha1
// (docs/engineering/02-repository-layout-and-conventions.md "Markers"): a
// kind, a field or an enum value this release does not serve.
type Feature struct {
	// Kind is the resource kind holding the feature.
	Kind v1alpha1.Kind
	// PolicyType is set for a field of a Policy config: only a Policy of
	// that spec.type holds it.
	PolicyType v1alpha1.PolicyType
	// Path is the schema path of the field or enum value
	// (schemaidx.Index.SchemaPath, such as "spec.listeners[].http3"); ""
	// for the whole kind.
	Path string
	// Value is the unserved enum value at Path; "" for a kind or a field.
	Value string
	// Milestone is the marker's milestone, such as "M3".
	Milestone string
}

// Features returns the served-feature table of this release, in kind,
// Policy type, path and value order.
func Features() []Feature { return plannedFeatures() }

// features indexes the served-feature table by kind.
type features struct {
	// kinds holds the row of each unserved kind.
	kinds map[v1alpha1.Kind]Feature
	// byPath holds the field and value rows of each kind by schema path.
	byPath map[v1alpha1.Kind]map[string][]Feature
}

// newFeatures indexes rows.
func newFeatures(rows []Feature) features {
	f := features{kinds: map[v1alpha1.Kind]Feature{}, byPath: map[v1alpha1.Kind]map[string][]Feature{}}
	for _, r := range rows {
		if r.Path == "" {
			f.kinds[r.Kind] = r
			continue
		}
		m := f.byPath[r.Kind]
		if m == nil {
			m = map[string][]Feature{}
			f.byPath[r.Kind] = m
		}
		m[r.Path] = append(m[r.Path], r)
	}
	return f
}

// CheckFeatures is the serve check of one resource of kind, named name,
// whose normalized envelope tree is root: it reports, as RZ-CFG-040, a
// kind this release does not serve, at the resource's kind, and each
// field or enum value of the served-feature table the resource holds with
// a value other than its schema default, at that field. A default stage G
// materialized, such as one an unserved field may carry, never refuses a
// Revision, and a field inside an unserved field or kind is not reported
// again. idx is the hub schema index the tree was normalized with, whose
// Walk gives the schema paths and defaults; loc maps a tree position to
// its source location (a zero location when nil). Policy types are
// CheckServed's. The error is idx.Walk's, for a kind idx does not hold.
func (r *Registry) CheckFeatures(idx *schemaidx.Index, kind v1alpha1.Kind, name string, root *tree.Node, loc func(tree.Pos) diag.Location) (diag.List, error) {
	at := func(n *tree.Node) diag.Location {
		if loc == nil || n == nil {
			return diag.Location{}
		}
		return loc(n.Pos)
	}
	res := &diag.ResourceID{Kind: string(kind), Name: name}
	if f, ok := r.features.kinds[kind]; ok {
		kn, _ := root.Get("kind")
		if kn == nil {
			kn = root
		}
		return diag.List{{
			Code: CodeUnserved, Severity: diag.SeverityError, Location: at(kn), Resource: res,
			Path:    diag.Path{diag.Field("kind")},
			Message: fmt.Sprintf("kind %q is not served by this release (Planned (%s))", kind, f.Milestone),
		}}, nil
	}
	rows := r.features.byPath[kind]
	if len(rows) == 0 {
		return nil, nil
	}
	policyType := ""
	if kind == v1alpha1.KindPolicy {
		if spec, ok := root.Get("spec"); ok {
			if t, ok := spec.Get("type"); ok && t.Kind == tree.KindString {
				policyType = t.Text
			}
		}
	}
	var out diag.List
	// paths[d] is the schema path at depth d, and nodes[d] its schema.
	var paths []string
	var nodes []*schemaidx.Node
	err := idx.Walk(string(kind), root, func(c *schemaidx.Cursor) error {
		d := c.Depth()
		paths, nodes = paths[:min(d, len(paths))], nodes[:min(d, len(nodes))]
		sp := ""
		if d > 0 && len(paths) == d {
			sp = childPath(paths[d-1], nodes[d-1], c)
		}
		paths, nodes = append(paths, sp), append(nodes, c.Info.Node)
		if c.Info.Node == nil {
			// Free content holds no table field.
			return schemaidx.ErrSkipChildren
		}
		for _, f := range rows[sp] {
			if f.PolicyType != "" && string(f.PolicyType) != policyType {
				continue
			}
			if !unserved(f, c) {
				continue
			}
			out = append(out, diag.Diagnostic{
				Code: CodeUnserved, Severity: diag.SeverityError, Location: at(c.Node), Resource: res,
				Path: c.Path(), Message: featureMessage(f),
			})
			return schemaidx.ErrSkipChildren
		}
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("registry: serve check of %s/%s: %w", kind, name, err)
	}
	return out, nil
}

// childPath returns the schema path of the position c names below the
// position at path, whose schema is parent: a declared member adds
// ".name", a typed-map value "{}" and a list element "[]", as
// schemaidx.Index.SchemaPath writes them.
func childPath(path string, parent *schemaidx.Node, c *schemaidx.Cursor) string {
	e, _ := c.Last()
	if e.Kind != diag.ElemField {
		return path + "[]"
	}
	if _, ok := parent.Property(e.Name); !ok {
		if _, typed := parent.Values(); typed {
			return path + "{}"
		}
	}
	if path == "" {
		return e.Name
	}
	return path + "." + e.Name
}

// unserved reports whether the position c holds the feature f with a
// value other than its schema default: a field present at all, an enum
// value equal to f.Value.
func unserved(f Feature, c *schemaidx.Cursor) bool {
	if f.Value != "" && (c.Node.Kind != tree.KindString || c.Node.Text != f.Value) {
		return false
	}
	def := c.Info.Node.DefaultNode()
	return def == nil || !bytes.Equal(schemaidx.AppendItemJSON(nil, c.Node), schemaidx.AppendItemJSON(nil, def))
}

// featureMessage returns the finding's message: the field, and the value
// for an enum value, with the milestone.
func featureMessage(f Feature) string {
	field := f.Path
	if i := strings.LastIndexByte(field, '.'); i >= 0 {
		field = field[i+1:]
	}
	field = strings.TrimRight(field, "[]{}")
	if f.Value != "" {
		return fmt.Sprintf("%s %s is not served by this release (Planned (%s))", field, strconv.Quote(f.Value), f.Milestone)
	}
	return fmt.Sprintf("field %s is not served by this release (Planned (%s))", strconv.Quote(field), f.Milestone)
}
