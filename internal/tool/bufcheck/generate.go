// generate runs buf generate into a temporary directory and compares its
// output with the -out directories, or with write makes them equal to it.
// It reports whether they were equal.
func (c checker) generate(ctx context.Context, outs []string, write bool) (bool, error) {
	tmp, err := os.MkdirTemp("", "bufcheck-generate-")
	if err != nil {
		return false, err
	}
	defer func() { _ = os.RemoveAll(tmp) }()
	var out bytes.Buffer
	//nolint:gosec // buf is the pinned binary make passes, run with fixed arguments.
	cmd := exec.CommandContext(ctx, c.buf, "generate", "--output", tmp)
	cmd.Dir = c.root
	cmd.Stdout, cmd.Stderr = &out, &out
	if err := cmd.Run(); err != nil {
		return false, fmt.Errorf("%w: buf generate: %w: %s", errBuf, err, strings.TrimSpace(out.String()))
	}
	generated, err := listFiles(tmp, false)
	if err != nil {
		return false, err
	}
	var outside []string
	for _, f := range generated {
		if !slices.ContainsFunc(outs, func(o string) bool { return strings.HasPrefix(f, o+"/") }) {
			outside = append(outside, f)
		}
	}
	if len(outside) > 0 {
		return false, fmt.Errorf("buf generate wrote %s outside the -out directories %s: name every output directory of buf.gen.yaml with -out",
			strings.Join(outside, ", "), strings.Join(outs, ", "))
	}
	var committed []string
	for _, o := range outs {
		files, err := listFiles(filepath.Join(c.root, filepath.FromSlash(o)), true)
		if err != nil {
			return false, err
		}
		for _, f := range files {
			committed = append(committed, o+"/"+f)
		}
	}
	diffs, err := compareTrees(tmp, c.root, generated, committed)
	if err != nil {
		return false, err
	}
	if !write {
		for _, d := range diffs {
			_, _ = fmt.Fprintln(c.stderr, d)
		}
		return len(diffs) == 0, nil
	}
	if err := applyDiffs(tmp, c.root, outs, diffs); err != nil {
		return false, err
	}
	_, _ = fmt.Fprintf(c.stdout, "bufcheck generate: %d file(s) of %s rewritten or removed\n", len(diffs), strings.Join(outs, ", "))
	return true, nil
}

// diffKind says how a committed output file differs from buf generate's.
type diffKind int

const (
	diffMissing diffKind = iota // generated, not committed
	diffChanged                 // committed with other bytes
	diffStale                   // committed, no longer generated
)

// diff is one finding of the comparison, at a slash-separated path relative
// to the repository root.
type diff struct {
	kind diffKind
	path string
}

func (d diff) String() string {
	switch d.kind {
	case diffMissing:
		return d.path + ": generated by buf generate but not committed"
	case diffChanged:
		return d.path + ": differs from what buf generate writes"
	case diffStale:
		return d.path + ": not written by buf generate: delete it, or restore the proto that generated it"
	default:
		return d.path + ": unknown difference"
	}
}

// compareTrees compares the generated files below genRoot with the
// committed ones below repoRoot; both lists are slash-separated paths
// relative to their roots, and the result is sorted by path.
func compareTrees(genRoot, repoRoot string, generated, committed []string) ([]diff, error) {
	var out []diff
	for _, f := range generated {
		want, err := os.ReadFile(filepath.Join(genRoot, filepath.FromSlash(f))) //nolint:gosec // A path buf generate wrote below the temporary directory.
		if err != nil {
			return nil, err
		}
		got, err := os.ReadFile(filepath.Join(repoRoot, filepath.FromSlash(f))) //nolint:gosec // A path below a -out directory of the repository.
		switch {
		case errors.Is(err, fs.ErrNotExist):
			out = append(out, diff{diffMissing, f})
		case err != nil:
			return nil, err
		case !bytes.Equal(got, want):
			out = append(out, diff{diffChanged, f})
		}
	}
	isGenerated := make(map[string]bool, len(generated))
	for _, f := range generated {
		isGenerated[f] = true
	}
	for _, f := range committed {
		if !isGenerated[f] {
			out = append(out, diff{diffStale, f})
		}
	}
	slices.SortFunc(out, func(a, b diff) int { return strings.Compare(a.path, b.path) })
	return out, nil
}

// applyDiffs makes the committed output equal to the generated one: it
// writes missing and changed files, deletes stale ones and then every
// directory below an -out directory that the deletions left empty.
func applyDiffs(genRoot, repoRoot string, outs []string, diffs []diff) error {
	var emptied []string
	for _, d := range diffs {
		target := filepath.Join(repoRoot, filepath.FromSlash(d.path))
		switch d.kind {
		case diffMissing, diffChanged:
			data, err := os.ReadFile(filepath.Join(genRoot, filepath.FromSlash(d.path))) //nolint:gosec // A path buf generate wrote below the temporary directory.
			if err != nil {
				return err
			}
			if err := os.MkdirAll(filepath.Dir(target), 0o750); err != nil {
				return err
			}
			if err := os.WriteFile(target, data, 0o600); err != nil { //nolint:gosec // target lies below an -out directory, at a path buf generate wrote.
				return err
			}
		case diffStale:
			if err := os.Remove(target); err != nil {
				return err
			}
			emptied = append(emptied, path.Dir(d.path))
		}
	}
	// Deepest first, so a parent left empty by its children goes too.
	slices.SortFunc(emptied, func(a, b string) int { return strings.Count(b, "/") - strings.Count(a, "/") })
	for _, dir := range emptied {
		for ; belowAny(dir, outs); dir = path.Dir(dir) {
			// Remove fails on a directory that still holds entries, which
			// ends the walk up.
			if err := os.Remove(filepath.Join(repoRoot, filepath.FromSlash(dir))); err != nil {
				break
			}
		}
	}
	return nil
}

// belowAny reports whether the slash-separated dir lies strictly below one
// of the -out directories.
func belowAny(dir string, outs []string) bool {
	return slices.ContainsFunc(outs, func(o string) bool { return strings.HasPrefix(dir, o+"/") })
}

// listFiles lists the regular files below root as sorted slash-separated
// relative paths; a missing root has none. With skipTests it leaves out Go
// test files and testdata directories, which are never generated output.
func listFiles(root string, skipTests bool) ([]string, error) {
	var out []string
	//nolint:gosec // root is the temporary output directory or an -out directory of the repository.
	err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			if p == root && errors.Is(err, fs.ErrNotExist) {
				return fs.SkipAll
			}
			return err
		}
		rel, err := filepath.Rel(root, p)
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		if d.IsDir() {
			if skipTests && d.Name() == "testdata" {
				return fs.SkipDir
			}
			return nil
		}
		if skipTests && strings.HasSuffix(rel, "_test.go") {
			return nil
		}
		if !d.Type().IsRegular() {
			return fmt.Errorf("%s is not a regular file", p)
		}
		out = append(out, rel)
		return nil
	})
	slices.Sort(out)
	return out, err
}
